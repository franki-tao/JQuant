    /**
     * JQuant-added behaviour regression (not an official test-suite case):
     * price a Bermudan, imply the Black volatility through
     * {@code EuropeanOption.impliedVolatility(process, ...)} (which uses the
     * FD engine for Bermudan exercise), reprice with that volatility and
     * check the round trip. This is self-consistency only.
     */
    @Test
    public void bermudanImpliedVolatilityRoundTrip() {
        final Date today = new Date(15, Month.JANUARY, 2026);
        Settings.instance.evaluationDate().equal(today);

        final DayCounter dc = new Actual360(false);
        final SimpleQuote spot = new SimpleQuote(100.0);
        final SimpleQuote qRate = new SimpleQuote(0.02);
        final SimpleQuote rRate = new SimpleQuote(0.05);
        final SimpleQuote vol = new SimpleQuote(0.20);
        final BlackScholesMertonProcess process = process(
                today, spot, qRate, rRate, vol, dc);

        final List<Date> dates = new ArrayList<>();
        for (int months = 3; months <= 12; months += 3) {
            dates.add(today.add(30 * months));
        }

        final Payoff payoff = new PlainVanillaPayoff(Option.Type.Put, 100.0);
        // impliedVolatility() prices trial volatilities on a 100x100 FD grid;
        // use the same grid here so the round trip is consistent.
        final EuropeanOption option =
                new EuropeanOption(payoff, new BermudanExercise(dates));
        option.setPricingEngine(
                new FdBlackScholesVanillaEngine(process, 100, 100));
        final double npv = option.NPV();

        final double implied = option.impliedVolatility(
                npv, process, 1.0e-8, 200, 1.0e-4, 4.0);

        final BlackScholesMertonProcess repricedProcess = process(
                today, spot, qRate, rRate, new SimpleQuote(implied), dc);
        option.setPricingEngine(
                new FdBlackScholesVanillaEngine(repricedProcess, 100, 100));
        final double repriced = option.NPV();

        final double error = Math.abs(repriced - npv);
        System.out.println("[E] npv=" + npv + " implied=" + implied
                + " repriced=" + repriced + " error=" + error);

        // impliedVolatility() solves to a price accuracy of 1e-8 on the same
        // 100x100 grid, so the reprice should agree well inside 1e-7.
        if (error > 1.0e-7) {
            fail("implied-volatility round trip failed: npv=" + npv
                    + " implied=" + implied + " repriced=" + repriced
                    + " error=" + error + " tolerance=1.0e-7");
        }
    }

