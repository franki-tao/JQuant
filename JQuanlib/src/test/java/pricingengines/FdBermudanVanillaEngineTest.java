    /**
     * JQuant-added behaviour regression (not an official test-suite case):
     * a Bermudan whose only exercise date is expiry must agree with the
     * European priced by the same engine and grid. This is a degeneracy
     * check, not independent correctness evidence.
     */
    @Test
    public void singleExpiryBermudanMatchesEuropeanOnSameGrid() {
        final Date today = new Date(15, Month.JANUARY, 2026);
        Settings.instance.evaluationDate().equal(today);

        final DayCounter dc = new Actual360(false);
        final SimpleQuote spot = new SimpleQuote(100.0);
        final SimpleQuote qRate = new SimpleQuote(0.02);
        final SimpleQuote rRate = new SimpleQuote(0.05);
        final SimpleQuote vol = new SimpleQuote(0.20);
        final BlackScholesMertonProcess process = process(
                today, spot, qRate, rRate, vol, dc);

        final Date maturity = today.add(360);
        final Payoff payoff = new PlainVanillaPayoff(Option.Type.Put, 100.0);
        final FdBlackScholesVanillaEngine engine =
                new FdBlackScholesVanillaEngine(process, 200, 400);

        final EuropeanOption european =
                new EuropeanOption(payoff, new EuropeanExercise(maturity));
        european.setPricingEngine(engine);

        final EuropeanOption bermudan = new EuropeanOption(
                payoff,
                new BermudanExercise(Collections.singletonList(maturity)));
        bermudan.setPricingEngine(engine);

        final double europeanNpv = european.NPV();
        final double bermudanNpv = bermudan.NPV();
        final double error = Math.abs(bermudanNpv - europeanNpv);

        System.out.println("[C] european=" + europeanNpv
                + " bermudan=" + bermudanNpv + " error=" + error);

        // Both options use the same 200x400 grid and the same engine. The
        // only difference is that the Bermudan condition replaces the
        // cell-averaged terminal value with the node payoff at expiry, so
        // the observed gap is at the discretisation-noise level.
        if (error > 1.0e-6) {
            fail("single-expiry Bermudan differs from European: european="
                    + europeanNpv + " bermudan=" + bermudanNpv
                    + " error=" + error + " tolerance=1.0e-6");
        }
    }

