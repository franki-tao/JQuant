    /**
     * JQuant-added comparison against independently generated official
     * QuantLib 1.44 values (not official test-suite cached values).
     *
     * <p>Market, dates, day counter, 100x100 Douglas grid and engine settings
     * are reproduced verbatim from
     * {@code /tmp/jquant-briefs/bermudan-official-refs.txt}. The
     * {@code FLOOR_GAP_POSSIBLE} rows in that file are intentionally excluded:
     * the file itself says they must not be used as tight expected values.
     */
    @Test
    public void matchesOfficialReferenceNpvs() {
        final Date today = new Date(15, Month.MAY, 2026);
        Settings.instance.evaluationDate().equal(today);
        final DayCounter dc = new Actual365Fixed();

        final Date maturity = new Date(15, Month.MAY, 2027);
        final List<Date> quarterlyDates = Arrays.asList(
                new Date(15, Month.AUGUST, 2026),
                new Date(15, Month.NOVEMBER, 2026),
                new Date(15, Month.FEBRUARY, 2027),
                maturity);

        // With the same engine, grid and market the remaining rows agree to
        // double-precision noise (observed errors are at most ~3e-14), so the
        // baseline absolute tolerance is 1e-9, about 1e-10 relative.
        for (ReferenceNpv row : OFFICIAL_REFERENCE) {
            final SimpleQuote spot = new SimpleQuote(row.spot());
            final SimpleQuote qRate = new SimpleQuote(row.q());
            final SimpleQuote rRate = new SimpleQuote(row.r());
            final SimpleQuote vol = new SimpleQuote(row.vol());
            final BlackScholesMertonProcess process = process(
                    today, spot, qRate, rRate, vol, dc);

            final Payoff payoff = new PlainVanillaPayoff(row.type(), row.strike());
            final Exercise exercise;
            switch (row.kind()) {
                case EUROPEAN:
                    exercise = new EuropeanExercise(maturity);
                    break;
                case BERMUDAN_SINGLE:
                    exercise = new BermudanExercise(
                            Collections.singletonList(maturity));
                    break;
                case BERMUDAN_QUARTERLY:
                    exercise = new BermudanExercise(quarterlyDates);
                    break;
                case AMERICAN:
                    exercise = new AmericanExercise(today, maturity);
                    break;
                default:
                    throw new IllegalArgumentException("unknown exercise kind");
            }

            final EuropeanOption option =
                    new EuropeanOption(payoff, exercise);
            option.setPricingEngine(
                    new FdBlackScholesVanillaEngine(process, 100, 100));
            final double calculated = option.NPV();
            final double error = Math.abs(calculated - row.expected());

            // The reference file documents that official 1.44 has no
            // settlement-date intrinsic floor while cf74c9f (and this port)
            // does. The floor only bites when the un-floored value is below
            // intrinsic, which is the case for the deep in-the-money American
            // put in market B. Its observed 6.35e-9 gap is exactly that known
            // engine difference, not a Bermudan-step-condition difference.
            final double tolerance =
                    row.kind() == ExerciseKind.AMERICAN
                            && payoff.value(row.spot()) >= row.expected()
                            ? 1.0e-8 : 1.0e-9;

            System.out.println("[F] " + row.name() + " expected="
                    + row.expected() + " calculated=" + calculated
                    + " error=" + error + " tolerance=" + tolerance);

            if (error > tolerance) {
                fail(row.name() + ": expected=" + row.expected()
                        + " calculated=" + calculated + " error=" + error
                        + " tolerance=" + tolerance);
            }
        }
    }

