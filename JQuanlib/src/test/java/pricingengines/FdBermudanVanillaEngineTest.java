    /**
     * JQuant-added behaviour regression (not an official test-suite case):
     * {@link FdmBermudanStepCondition#applyTo} leaves the grid untouched
     * unless {@code t} is exactly one of {@code exerciseTimes()}.
     */
    @Test
    public void bermudanConditionAppliesOnlyAtExerciseTimes() {
        final Date today = new Date(15, Month.JANUARY, 2026);
        Settings.instance.evaluationDate().equal(today);

        final DayCounter dc = new Actual360(false);
        final SimpleQuote spot = new SimpleQuote(100.0);
        final SimpleQuote qRate = new SimpleQuote(0.0);
        final SimpleQuote rRate = new SimpleQuote(0.05);
        final SimpleQuote vol = new SimpleQuote(0.20);
        final BlackScholesMertonProcess process = process(
                today, spot, qRate, rRate, vol, dc);

        final Date maturity = today.add(360);
        final double maturityTime = dc.yearFraction(today, maturity);
        final Payoff payoff = new PlainVanillaPayoff(Option.Type.Call, 100.0);

        final FdmMesher mesher = new FdmMesherComposite(
                new FdmBlackScholesMesher(
                        101, process, maturityTime, 100.0,
                        Double.NaN, Double.NaN, 0.0001, 1.5,
                        new Point<>(100.0, 0.1),
                        Collections.emptyList(), null, 0.0));
        final FdmLogInnerValue calculator =
                new FdmLogInnerValue(payoff, mesher, 0);

        final Date firstExercise = today.add(90);
        final Date secondExercise = today.add(180);
        final List<Date> exerciseDates =
                Arrays.asList(firstExercise, secondExercise);

        final FdmBermudanStepCondition condition =
                new FdmBermudanStepCondition(exerciseDates, today, dc,
                        mesher, calculator);

        final List<Double> exerciseTimes = condition.exerciseTimes();
        assertEquals(2, exerciseTimes.size());
        assertEquals(dc.yearFraction(today, firstExercise),
                exerciseTimes.get(0), 0.0);
        assertEquals(dc.yearFraction(today, secondExercise),
                exerciseTimes.get(1), 0.0);

        // Away from an exercise time the all-zero array must stay all zero,
        // both before the first date and between/after the dates.
        final double[] untouchedTimes = {
                exerciseTimes.get(0) * 0.5,
                exerciseTimes.get(0) + 1.0e-9,
                (exerciseTimes.get(0) + exerciseTimes.get(1)) / 2.0,
                exerciseTimes.get(1) + 1.0e-6
        };
        for (double t : untouchedTimes) {
            final Array a =
                    new Array(mesher.layout().size());
            condition.applyTo(a, t);
            for (double value : a.toArray()) {
                assertEquals(0.0, value, 0.0,
                        "grid changed at non-exercise time " + t);
            }
        }

        // At an exercise time every node is floored by its inner value.
        final Array a =
                new Array(mesher.layout().size());
        condition.applyTo(a, exerciseTimes.get(0));
        boolean sawPositive = false;
        for (FdmLinearOpIterator
                iter : mesher.layout()) {
            final double expected = payoff.value(
                    Math.exp(mesher.location(iter, 0)));
            assertEquals(expected, a.get(iter.index()), 0.0,
                    "wrong inner value at node " + iter.index());
            sawPositive |= expected > 0.0;
        }
        assertTrue(sawPositive, "test grid did not reach the in-the-money region");
    }

    // ------------------------------------------------------------------
    // B. Settlement-date exercise and intrinsic-value flooring
    // ------------------------------------------------------------------

    /**
     * JQuant-added behaviour regression (not an official test-suite case):
     * when today is itself an exercise date, the engine value must not fall
     * below immediate intrinsic. When today is deliberately omitted the
     * value may fall below intrinsic for a deep in-the-money call with a
     * dividend yield above the risk-free rate.
     */
    @Test
    public void bermudanTodayExerciseFloorsValueAtIntrinsic() {
        final Date today = new Date(15, Month.JANUARY, 2026);
        Settings.instance.evaluationDate().equal(today);

        final DayCounter dc = new Actual360(false);
        final SimpleQuote spot = new SimpleQuote(150.0);
        final SimpleQuote qRate = new SimpleQuote(0.10);
        final SimpleQuote rRate = new SimpleQuote(0.0);
        final SimpleQuote vol = new SimpleQuote(0.15);
        final BlackScholesMertonProcess process = process(
                today, spot, qRate, rRate, vol, dc);

        final Payoff payoff = new PlainVanillaPayoff(Option.Type.Call, 100.0);
        final double intrinsic = payoff.value(spot.value());

        final List<Date> withToday = new ArrayList<>();
        final List<Date> withoutToday = new ArrayList<>();
        withToday.add(today);
        for (int months = 3; months <= 12; months += 3) {
            final Date date = today.add(30 * months);
            withToday.add(date);
            withoutToday.add(date);
        }

        final FdBlackScholesVanillaEngine engine =
                new FdBlackScholesVanillaEngine(process, 200, 400);

        final EuropeanOption withTodayOption = new EuropeanOption(
                payoff, new BermudanExercise(withToday));
        withTodayOption.setPricingEngine(engine);
        final double withTodayNpv = withTodayOption.NPV();

        final EuropeanOption withoutTodayOption = new EuropeanOption(
                payoff, new BermudanExercise(withoutToday));
        withoutTodayOption.setPricingEngine(engine);
        final double withoutTodayNpv = withoutTodayOption.NPV();

        System.out.println("[B] intrinsic=" + intrinsic
                + " withToday=" + withTodayNpv
                + " withoutToday=" + withoutTodayNpv);

        // The extra exercise opportunity cannot reduce the value, and the
        // exercise on the settlement date floors the reported NPV.
        assertTrue(withTodayNpv >= intrinsic - 1.0e-10,
                "value with exercise today below intrinsic: npv="
                        + withTodayNpv + " intrinsic=" + intrinsic);
        assertTrue(withTodayNpv >= withoutTodayNpv - 1.0e-10,
                "adding an exercise date reduced the value: with="
                        + withTodayNpv + " without=" + withoutTodayNpv);
        // For this deep in-the-money call the holder wants to exercise now;
        // with today removed the FD value can be below immediate intrinsic.
        assertTrue(withoutTodayNpv < intrinsic,
                "scenario did not exercise below intrinsic: without="
                        + withoutTodayNpv + " intrinsic=" + intrinsic);
    }

